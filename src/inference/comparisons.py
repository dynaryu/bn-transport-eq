"""Deterministic plans and arithmetic; all probabilities come from engine.answer."""
from __future__ import annotations

import copy
import itertools
import json
from pathlib import Path

import networkx as nx
from jsonschema import Draft202012Validator

from . import engine

SCHEMA = json.loads(Path(__file__).with_name("analysis.schema.json").read_text(encoding="utf-8"))


def readback(task):
    kind = task["kind"]
    if kind == "compare":
        return "I’ll compare the baseline with each named variant and report baseline minus variant in percentage points."
    if kind == "importance":
        return ("I’ll compare system failure with each selected bridge’s edge forced closed versus open. " +
                ("All other bridged edges will be forced open." if task.get("topology_only") else
                 "Other bridges retain their scenario-driven uncertainty."))
    if kind == "paths":
        return (f"I’ll evaluate up to {task.get('limit', 10)} shortest-time paths from {task['origin']} to "
                f"{task['destination']}, using each path’s joint survival probability.")
    return ("I’ll minimise expected loss before inspection and after each possible inspection result, "
            "then subtract inspection cost in the supplied loss units.")


def merge(base, changes):
    out = copy.deepcopy(base)
    for key, value in changes.items():
        out[key] = merge(out.get(key, {}), value) if isinstance(value, dict) else copy.deepcopy(value)
    return out


def validate(task):
    errors = list(Draft202012Validator(SCHEMA).iter_errors(task))
    if errors:
        raise engine.QueryError("; ".join(e.message for e in errors[:4]))
    allowed = {"compare": {"variants"}, "importance": {"bridges", "topology_only"},
               "paths": {"origin", "destination", "limit"},
               "voi": {"state_nodes", "loss_units", "actions", "inspections"}}
    extras = set(task) - {"kind", "query"} - allowed[task["kind"]]
    if extras:
        raise engine.QueryError(f"Unused arguments for {task['kind']}: {', '.join(sorted(extras))}")
    if task["kind"] in ("paths", "voi") and any(k in task["query"] for k in ("events", "targets", "joint_events")):
        raise engine.QueryError("Paths/VOI query contains scenario settings only; its events are generated by the analysis")


def execute(task, run=None):
    validate(task)
    run = run or (lambda q: engine.answer(q, record={"source": "analysis"}))
    base = task["query"]
    kind = task["kind"]
    if kind == "voi":
        from .decision import evaluate
        return evaluate(task, run)
    if kind == "paths":
        return paths(task, run)
    if not base.get("events") or len(base["events"]) != 1 or "*" in base["events"][0]["node"]:
        raise engine.QueryError("Comparison/importance needs one exact system-failure event")
    if base.get("targets") or base.get("joint_events"):
        raise engine.QueryError("Comparison/importance accepts only its single event")
    # Validate before any work is performed.
    engine.scope(base)
    rows = []
    if kind == "compare":
        for variant in task["variants"]:
            if set(variant["changes"]) - {"rows", "parameters", "parameter_sets", "do"}:
                raise engine.QueryError("A variant may change scenario inputs or do(), not the reported event/evidence")
            engine.scope(merge(base, variant["changes"]))
        baseline = run(base)
        p0 = baseline["events"][0]["p"]
        for variant in task["variants"]:
            result = run(merge(base, variant["changes"]))
            p = result["events"][0]["p"]
            rows.append({"name": variant["name"], "baseline_p": p0, "variant_p": p,
                         "reduction_pp": 100 * (p0 - p)})
    else:
        compiled = engine.compile_query(base)
        edge_of = {r["id"]: r["edge"] for r in compiled.network.rows("Bridge")}
        if not set(task["bridges"]) <= set(edge_of):
            raise engine.QueryError("Importance names an unknown bridge")
        # A bridge is forced closed or open through its edge, which is exact when the edge carries
        # only that bridge: forcing a shared edge open would force its other bridges open too.
        shared = [b for b in task["bridges"] if list(edge_of.values()).count(edge_of[b]) > 1]
        if shared:
            raise engine.QueryError(f"Bridge importance needs one bridge per edge; {', '.join(shared)} share theirs")
        for bridge in task["bridges"]:
            forced = {f"EdgeOpen::{e}": 1 for e in set(edge_of.values())} if task.get("topology_only") else {}
            closed = run(merge(base, {"do": {**forced, f"EdgeOpen::{edge_of[bridge]}": 0}}))
            opened = run(merge(base, {"do": {**forced, f"EdgeOpen::{edge_of[bridge]}": 1}}))
            pc, po = closed["events"][0]["p"], opened["events"][0]["p"]
            rows.append({"bridge": bridge, "forced_closed_p": pc, "forced_open_p": po,
                         "importance": pc - po})
        rows.sort(key=lambda r: r["importance"], reverse=True)
    return {"kind": kind, "rows": rows,
            "note": "Monte Carlo point estimates; differences have no paired confidence interval. "
                    "Reusing a seed alone does not guarantee paired random draws across changed models."}


def paths(task, run):
    compiled = engine.compile_query(task["query"])
    graph = nx.Graph()
    graph.add_nodes_from(r["id"] for r in compiled.network.rows("Node"))
    for edge in compiled.network.rows("Edge"):
        if graph.has_edge(edge["source"], edge["target"]):
            raise engine.QueryError("Parallel edges need an explicit multigraph path implementation")
        graph.add_edge(edge["source"], edge["target"], id=edge["id"],
                       time=edge["length_km"] / edge["avg_speed_kph"])
    origin, destination = task["origin"], task["destination"]
    if origin == destination:
        raise engine.QueryError("Origin already equals destination; no route is needed")
    try:
        candidates = list(itertools.islice(nx.shortest_simple_paths(graph, origin, destination, weight="time"),
                                          task.get("limit", 10)))
    except (nx.NetworkXNoPath, nx.NodeNotFound) as exc:
        raise engine.QueryError(str(exc)) from exc
    routes, events = [], []
    for i, path in enumerate(candidates):
        edges = [graph[a][b] for a, b in zip(path, path[1:])]
        name = f"path-{i + 1}"
        routes.append({"name": name, "nodes": path, "edges": [e["id"] for e in edges],
                       "travel_time_h": sum(e["time"] for e in edges)})
        events.append({"name": name, "expression": {"all": [
            {"node": f"EdgeOpen::{e['id']}", "op": "==", "value": "True"} for e in edges]}})
    query = {k: v for k, v in task["query"].items() if k not in ("events", "targets", "joint_events")}
    result = run({**query, "joint_events": events})
    for route, event in zip(routes, result["events"]):
        route.update(p=event["p"], ci95=event["ci95"])
    routes.sort(key=lambda r: (-r["p"], r["travel_time_h"]))
    return {"kind": "paths", "rows": routes, "recommendation": routes[0]["name"],
            "note": "Highest estimated survival among the evaluated shortest-time candidate paths; "
                    "not a guarantee of the globally most reliable route."}
